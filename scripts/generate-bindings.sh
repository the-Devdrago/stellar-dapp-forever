#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(dirname "$SCRIPT_DIR")"

# Build the contract wasm if not already built
if [ ! -f "$PROJECT_DIR/target/wasm32v1-none/release/stellar_dapp_forever.optimized.wasm" ]; then
  echo "Building wasm..."
  cd "$PROJECT_DIR"
  cargo build --locked --target wasm32v1-none --release
fi

# Generate TypeScript bindings
BINDINGS_DIR="$PROJECT_DIR/bindings/ts"
mkdir -p "$BINDINGS_DIR"

# Remove existing contents (except .gitkeep)
find "$BINDINGS_DIR" -mindepth 1 ! -name '.gitkeep' -delete 2>/dev/null || true

# Run stellar contract generate-bindings if available, otherwise create stubs
if command -v stellar &>/dev/null; then
  stellar contract generate-bindings \
    --wasm "$PROJECT_DIR/target/wasm32v1-none/release/stellar_dapp_forever.optimized.wasm" \
    --output "$BINDINGS_DIR"
else
  echo "⚠ stellar CLI not found, creating minimal TypeScript bindings stubs"
  cat > "$BINDINGS_DIR/index.ts" <<'EOF'
/**
 * TypeScript bindings for stellar-dapp-forever contract
 * Generated by scripts/generate-bindings.sh
 *
 * This is a stub. Run `scripts/generate-bindings.sh` after installing the
 * stellar CLI to generate full bindings from the WASM.
 */
export {};
EOF
fi

echo "TypeScript bindings generated at $BINDINGS_DIR"